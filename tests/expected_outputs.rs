/// The ACadSharp version the lock file actually pins.
///
/// Read from the lock rather than the csproj because the lock is what
/// `--locked-mode` enforces, so it is the one that cannot be wrong about what
/// a restore installs.
fn locked_acadsharp_version() -> String {
    let path = reference_project().join("packages.lock.json");
    let text = std::fs::read_to_string(&path)
        .unwrap_or_else(|e| panic!("{} must be readable: {e}", path.display()));
    let lock: Value = serde_json::from_str(&text).expect("packages.lock.json must be JSON");

    let mut found = Vec::new();
    for framework in lock["dependencies"]
        .as_object()
        .expect("dependencies")
        .values()
    {
        if let Some(resolved) = framework["ACadSharp"]["resolved"].as_str() {
            found.push(resolved.to_string());
        }
    }
    assert_eq!(
        found.len(),
        1,
        "expected exactly one locked ACadSharp, found {found:?}"
    );
    found.remove(0)
}

fn pinned_sdk_version() -> String {
    let path = repo_root().join("reference").join("global.json");
    let text = std::fs::read_to_string(&path)
        .unwrap_or_else(|e| panic!("{} must be readable: {e}", path.display()));
    let global: Value = serde_json::from_str(&text).expect("global.json must be JSON");
    global["sdk"]["version"]
        .as_str()
        .expect("global.json must pin sdk.version")
        .to_string()
}

