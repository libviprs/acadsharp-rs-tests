#!/usr/bin/env python3
"""Make and verify the code page fixtures (R5.4, acadsharp-rs-tests#30).

`fixtures/codepage_plan.toml` lists one authored drawing per code page family, written at
AC1015 and AC1018 by ACadSharp and by acadrust as a DWG and as a pre-2007 ASCII DXF
(112 outputs). This tool makes the files, freezes the oracle's reading of each, and records
every output as an `[[authored]]` row of `fixtures/manifest.toml`. All of them are stored
(compressed under `fixtures/authored/`): each is a few kilobytes, and an ACadSharp output
cannot be made again without .NET.

    python3 tools/regenerate_codepage.py verify
    python3 tools/regenerate_codepage.py regenerate --acadrust-dir DIR [--accept]

ACadSharp writes through the oracle's `--author-to` (twice per output, and a pair that
differs fails the run); acadrust through `src/bin/author-acadrust.rs`, whose directory this
takes with `--acadrust-dir`. A write a library refuses is a row saying so, never a hole.
Needs Python 3.14 (it reuses `regenerate_reference`'s zstd settings).
"""

from __future__ import annotations

import argparse
import pathlib
import shutil
import subprocess
import sys
import tempfile
import tomllib

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

import regenerate_reference as ref  # noqa: E402

ROOT = ref.ROOT
MANIFEST = ref.MANIFEST
FIXTURE_DIR = ref.FIXTURE_DIR
OUT_DIR = FIXTURE_DIR / "authored"
PLAN = FIXTURE_DIR / "codepage_plan.toml"
ACADRUST_REV = ROOT / "ACADRUST_REV"

MARK = "# ---- authored code page drawings: generated by tools/regenerate_codepage.py, do not edit ----"
END = "# ---- end of the authored drawings ----"
ORACLE_AS = {"dwg": "dwg", "dxf-ascii": "dxf"}
ROW_KEYS = (
    "writer", "page", "container", "version", "file", "bytes", "sha256",
    "generated_by", "writer_version", "write_failed",
    "reference_jsonl", "reference_jsonl_uncompressed_sha256", "no_reference",
    "acadsharp_reference_version", "acadsharp_reference_commit", "dotnet_sdk",
    "reference_schema",
)
INT_KEYS = frozenset({"page", "bytes", "reference_schema"})


def load_plan() -> dict:
    with PLAN.open("rb") as handle:
        return tomllib.load(handle)


def texts_of(family: dict, plan: dict) -> list[str]:
    out = [family["held"], plan["unheld"]["text"], family["literal"]]
    if family.get("mif"):
        out.append(family["mif"])
    return out


def output_id(writer: str, page: int, container: str, version: str) -> str:
    """Kept in step with `Output::id` in src/codepage.rs; tests/codepage.rs holds the two to
    the same list."""
    return f"cp-{writer}-{page}-{container}-{version.lower()}"


def outputs(plan: dict) -> list[dict]:
    rows = []
    for family in plan["family"]:
        for writer in plan["writers"]:
            for container in plan["containers"]:
                for version in plan["versions"]:
                    rows.append({
                        "id": output_id(writer, family["page"], container, version),
                        "writer": writer, "page": family["page"], "container": container,
                        "version": version, "family": family,
                        "ext": "dwg" if container == "dwg" else "dxf",
                    })
    return sorted(rows, key=lambda r: r["id"])


def pinned_acadrust() -> str:
    for line in ACADRUST_REV.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line and not line.startswith("#"):
            return line
    raise SystemExit(f"{ACADRUST_REV} holds no pin")


def render_rows(rows: list[dict]) -> str:
    out = [MARK, ""]
    for row in rows:
        out.append("[[authored]]")
        out.append(f'id = "{row["id"]}"')
        for key in ROW_KEYS:
            if key not in row:
                continue
            value = row[key]
            if key in INT_KEYS:
                out.append(f"{key} = {value}")
            else:
                escaped = str(value).replace("\\", "\\\\").replace('"', '\\"')
                out.append(f'{key} = "{escaped}"')
        out.append("")
    out.append(END)
    return "\n".join(out) + "\n"


def rewrite_manifest(text: str, rows: list[dict]) -> str:
    block = render_rows(rows)
    if MARK in text:
        head, _, rest = text.partition(MARK)
        tail = rest.partition(END)[2] if END in rest else ""
        tail = tail.lstrip("\n")
        return head.rstrip("\n") + "\n\n" + block + (("\n" + tail) if tail else "")
    return text.rstrip("\n") + "\n\n" + block


def first_line(text: str) -> str:
    for line in text.splitlines():
        if line.strip():
            return line.strip()
    return ""


def command_verify(_args: argparse.Namespace) -> int:
    manifest = ref.load_manifest()
    plan = load_plan()
    want = {o["id"]: o for o in outputs(plan)}
    rows = manifest.get("authored", [])
    have = {r["id"]: r for r in rows}
    problems = [f"{i}: in the plan and not in the manifest" for i in sorted(set(want) - set(have))]
    problems += [f"{i}: in the manifest and not in the plan" for i in sorted(set(have) - set(want))]
    acadrust = pinned_acadrust()
    locked = ref.locked_acadsharp_version()
    for row in rows:
        rid = row["id"]
        spec = want.get(rid)
        if spec is None:
            continue
        for key in ("writer", "page", "container", "version"):
            if row.get(key) != spec[key]:
                problems.append(f"{rid}: {key} is {row.get(key)!r}, the plan says {spec[key]!r}")
        expected_writer = f"acadrust@{acadrust}" if row["writer"] == "acadrust" else f"ACadSharp {locked}"
        if row.get("writer_version") != expected_writer:
            problems.append(f"{rid}: writer_version {row.get('writer_version')!r}, expected {expected_writer!r}")
        if row.get("write_failed"):
            if "file" in row:
                problems.append(f"{rid}: write_failed and a file")
            continue
        path = FIXTURE_DIR / row["file"]
        if not path.is_file():
            problems.append(f"{rid}: {path} is missing")
            continue
        data = ref.decompress(path.read_bytes())
        if ref.sha256_bytes(data) != row["sha256"] or len(data) != row["bytes"]:
            problems.append(f"{rid}: the output is not the bytes the manifest froze")
        if row.get("no_reference"):
            if "reference_jsonl" in row:
                problems.append(f"{rid}: no_reference and a reference")
            continue
        if "reference_jsonl" not in row:
            problems.append(f"{rid}: no oracle reading and no no_reference reason")
            continue
        rpath = FIXTURE_DIR / row["reference_jsonl"]
        if not rpath.is_file():
            problems.append(f"{rid}: {rpath} is missing")
            continue
        if ref.sha256_bytes(ref.decompress(rpath.read_bytes())) != row["reference_jsonl_uncompressed_sha256"]:
            problems.append(f"{rid}: the oracle's reading is not the one the manifest froze")
    for problem in problems:
        print(f"error: {problem}", file=sys.stderr)
    if problems:
        print(f"{len(problems)} problem(s)", file=sys.stderr)
        return 1
    print(f"verified {len(rows)} authored drawing(s) against fixtures/manifest.toml")
    return 0


def oracle(dotnet: list[str], *args: str) -> subprocess.CompletedProcess:
    command = dotnet + ["run", "--no-build", "--no-restore", "-c", "Release",
                        "--project", "reference/ACadSharp.Reference", "--", *args]
    print("$ oracle " + " ".join(args[:6]) + " ...")
    return subprocess.run(command, cwd=ROOT, check=False, capture_output=True, text=True)


def command_regenerate(args: argparse.Namespace) -> int:
    manifest = ref.load_manifest()
    plan = load_plan()
    wanted = outputs(plan)
    acadsharp = ref.locked_acadsharp_version()
    sdk = ref.pinned_sdk_version()
    acadrust_dir = pathlib.Path(args.acadrust_dir) if args.acadrust_dir else None
    if acadrust_dir is None:
        print("error: --acadrust-dir is required (run src/bin/author-acadrust.rs first)", file=sys.stderr)
        return 1
    with tempfile.TemporaryDirectory(prefix="acadsharp-codepage-") as staging_name:
        staging = pathlib.Path(staging_name)
        ref.STAGING_MOUNT[0] = str(staging)
        dotnet = ref.choose_runner(args.runner, args.image)
        mount = "/staging" if dotnet[0] == "docker" else str(staging)
        ref.run(dotnet + ["restore", "reference/ACadSharp.Reference/ACadSharp.Reference.csproj",
                          "--locked-mode", "-v", "q"], what="dotnet restore --locked-mode")
        ref.run(dotnet + ["build", "reference/ACadSharp.Reference/ACadSharp.Reference.csproj",
                          "-c", "Release", "--no-restore", "-v", "q"], what="dotnet build")
        for sub in ("gen1", "gen2", "files", "read"):
            (staging / sub).mkdir()
        rows = []
        for o in wanted:
            rid, ext = o["id"], o["ext"]
            row = {"id": rid, "writer": o["writer"], "page": o["page"], "container": o["container"],
                   "version": o["version"]}
            if o["writer"] == "acadsharp":
                row["generated_by"] = "reference/ACadSharp.Reference --author-to (tools/regenerate_codepage.py)"
                row["writer_version"] = f"ACadSharp {acadsharp}"
                failure = None
                for n in ("gen1", "gen2"):
                    cmd = ["--author-to", f"{mount}/{n}/{rid}.{ext}", "--as", ORACLE_AS[o["container"]],
                           "--version", o["version"], "--codepage", o["family"]["header"]]
                    for t in texts_of(o["family"], plan):
                        cmd += ["--text", t]
                    done = oracle(dotnet, *cmd)
                    if done.returncode != 0:
                        failure = first_line(done.stderr) or f"exit {done.returncode}"
                        break
                if failure:
                    row["write_failed"] = failure
                    rows.append(row)
                    continue
                a, b = (staging / n / f"{rid}.{ext}" for n in ("gen1", "gen2"))
                if a.read_bytes() != b.read_bytes():
                    print(f"error: {rid}: two writes of one output differ", file=sys.stderr)
                    return 1
                shutil.copy(a, staging / "files" / f"{rid}.{ext}")
            else:
                row["generated_by"] = "src/bin/author-acadrust.rs (tools/regenerate_codepage.py)"
                row["writer_version"] = f"acadrust@{pinned_acadrust()}"
                error = acadrust_dir / f"{rid}.error.txt"
                produced = acadrust_dir / f"{rid}.{ext}"
                if error.is_file():
                    row["write_failed"] = first_line(error.read_text(encoding="utf-8"))
                    rows.append(row)
                    continue
                if not produced.is_file():
                    print(f"error: {rid}: {produced} is not in --acadrust-dir", file=sys.stderr)
                    return 1
                shutil.copy(produced, staging / "files" / f"{rid}.{ext}")
            data = (staging / "files" / f"{rid}.{ext}").read_bytes()
            row["file"] = f"authored/{rid}.{ext}.zst"
            row["bytes"] = len(data)
            row["sha256"] = ref.sha256_bytes(data)
            done = oracle(dotnet, f"{mount}/files/{rid}.{ext}", "--jsonl", f"{mount}/read/{rid}.reference.jsonl")
            reading = staging / "read" / f"{rid}.reference.jsonl"
            if done.returncode != 0 or not reading.is_file():
                row["no_reference"] = first_line(done.stderr) or f"exit {done.returncode}"
            else:
                jsonl = reading.read_bytes()
                row["reference_jsonl"] = f"authored/{rid}.reference.jsonl.zst"
                row["reference_jsonl_uncompressed_sha256"] = ref.sha256_bytes(jsonl)
                row["acadsharp_reference_version"] = acadsharp
                row["acadsharp_reference_commit"] = manifest["upstream"]["commit"]
                row["dotnet_sdk"] = sdk
                row["reference_schema"] = ref.REFERENCE_SCHEMA
            rows.append(row)
        committed = {r["id"]: r for r in manifest.get("authored", [])}
        changed = [f"{r['id']}: " + ("new" if r["id"] not in committed else "moved")
                   for r in rows if r["id"] not in committed or any(committed[r["id"]].get(k) != r.get(k) for k in ROW_KEYS)]
        for line in changed:
            print(f"  {line}")
        if not changed:
            print("no differences; nothing to accept")
            return 0
        if not args.accept:
            print(f"\n{len(changed)} difference(s) and --accept was not given, so nothing was written.")
            return 1
        OUT_DIR.mkdir(parents=True, exist_ok=True)
        for row in rows:
            if "file" in row:
                data = (staging / "files" / pathlib.Path(row["file"]).name.removesuffix(".zst")).read_bytes()
                (FIXTURE_DIR / row["file"]).write_bytes(ref.compress(data))
            if "reference_jsonl" in row:
                jsonl = (staging / "read" / f"{row['id']}.reference.jsonl").read_bytes()
                (FIXTURE_DIR / row["reference_jsonl"]).write_bytes(ref.compress(jsonl))
        MANIFEST.write_text(rewrite_manifest(MANIFEST.read_text(encoding="utf-8"), rows), encoding="utf-8")
        print(f"\naccepted: wrote {len(rows)} authored row(s)")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="command")
    sub.add_parser("verify").set_defaults(handler=command_verify)
    regenerate = sub.add_parser("regenerate")
    regenerate.add_argument("--accept", action="store_true")
    regenerate.add_argument("--acadrust-dir")
    regenerate.add_argument("--runner", choices=("auto", "dotnet", "docker"), default="auto")
    regenerate.add_argument("--image", default=ref.DEFAULT_IMAGE)
    regenerate.set_defaults(handler=command_regenerate)
    args = parser.parse_args(argv)
    if not getattr(args, "handler", None):
        args = parser.parse_args(["verify"])
    return args.handler(args)


if __name__ == "__main__":
    raise SystemExit(main())
