"""AutoCAD's own DXF, read by ezdxf, written as canonical schema 1 (R3.4).

Ground truth for the parity run: a reader that shares no code with ACadSharp,
acadrust or acadsharp-rs, over files AutoCAD itself wrote. ezdxf never opens a
DWG, so this cannot be the oracle's DWG reader wearing a different hat.

Two halves, kept apart on purpose.

    extract   needs ezdxf. Runs inside the pinned container. Reads the DXF twins
              the manifest lists (`[[oracle_input]]`) and writes, per input,
              `<id>.ezdxf.jsonl` (schema 1), `<id>.ezdxf.src.jsonl` (the
              sidecar) and `<id>.ezdxf.run.json` into a directory.
    freeze    stdlib only (and `compression.zstd`). Drives `extract` in that
              container, compares with what is committed, and with `--accept`
              writes `fixtures/ground_truth/ezdxf/` and the manifest rows.
    verify    stdlib only, offline: the committed files are the ones the
              manifest froze.

    tools/ground_truth/extract_ezdxf.py verify
    tools/ground_truth/extract_ezdxf.py freeze            # reports, writes nothing
    tools/ground_truth/extract_ezdxf.py freeze --accept   # writes

`freeze` never touches a committed file without `--accept`, for the reason
`tools/regenerate_reference.py` gives: a moved ground truth has to arrive as a
reviewed diff.

What is ezdxf's and what is mine. Reading, the block table, OCS handling for
entities, hatch paths, spline and ellipse parameters: ezdxf. The schema's own
conventions (record order, perimeter order for SOLID, the arbitrary-axis frame
a record is written in, the SVD for a curve under a non-uniform scale, the
warning vocabulary) are the schema's, and are written here from
`docs/CANONICAL_SCHEMA.md`, not copied from either reader. Two ezdxf choices
that differ from the schema are listed in `docs/EMITTERS.md` (section ezdxf).
`ezdxf.path` is never used: it approximates arcs with Beziers.
"""

