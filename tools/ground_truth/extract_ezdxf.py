def zstd_module():
    if sys.version_info < (3, 14):
        sys.exit("freeze needs Python 3.14 for compression.zstd; run it in the pinned image")
    from compression import zstd

    return zstd


def compress(data: bytes) -> bytes:
    zstd = zstd_module()
    return zstd.compress(
        data,
        options={
            zstd.CompressionParameter.compression_level: 19,
            zstd.CompressionParameter.content_size_flag: 1,
            zstd.CompressionParameter.checksum_flag: 0,
            zstd.CompressionParameter.dict_id_flag: 0,
            zstd.CompressionParameter.nb_workers: 0,
        },
    )


def decompress(data: bytes) -> bytes:
    return zstd_module().decompress(data)


def run_extract_in_container(image: str, only: list[str] | None) -> dict[str, bytes]:
    """Run `extract` in the pinned image and return {file name: bytes}.

    The inputs go in and the outputs come out as tar streams, so this works
    against a docker daemon on another machine (DOCKER_HOST=ssh://...), where a
    bind mount would resolve on the wrong host.
    """
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w") as tar:
        def add(path: pathlib.Path, arc: str):
            info = tar.gettarinfo(str(path), arc)
            info.uid = info.gid = 0
            info.uname = info.gname = ""
            with open(path, "rb") as fh:
                tar.addfile(info, fh)

        add(MANIFEST, "w/fixtures/manifest.toml")
        add(TOOL_DIR / "extract_ezdxf.py", "w/tools/ground_truth/extract_ezdxf.py")
        add(REQUIREMENTS, "w/tools/ground_truth/requirements.txt")
        manifest = load_manifest()
        for row in inputs(manifest):
            add(FIXTURES / row["file"], f"w/fixtures/{row['file']}")
    only_args = "".join(f" --only {o}" for o in (only or []))
    script = (
        "set -e; mkdir -p /w && tar -x -C /w && cd /w && "
        "pip install -q --no-cache-dir --require-hashes -r tools/ground_truth/requirements.txt >&2 && "
        "python tools/ground_truth/extract_ezdxf.py extract --manifest fixtures/manifest.toml "
        f"--dxf-root fixtures --out /out{only_args} >&2 && tar -c -C /out ."
    )
    cmd = [
        "docker", "run", "--rm", "-i", "--platform", "linux/amd64",
        "-e", f"GT_IMAGE={image}", "-e", "PYTHONHASHSEED=0",
        image, "sh", "-c", script,
    ]
    print("$ " + " ".join(cmd[:8]) + " ... " + image)
    proc = subprocess.run(cmd, input=buf.getvalue(), stdout=subprocess.PIPE, check=False)
    if proc.returncode != 0:
        sys.exit(f"extraction failed with exit code {proc.returncode}")
    files = {}
    with tarfile.open(fileobj=io.BytesIO(proc.stdout), mode="r") as tar:
        for member in tar.getmembers():
            if member.isfile():
                files[pathlib.PurePosixPath(member.name).name] = tar.extractfile(member).read()
    return files


MANIFEST_KEYS = (
    "file", "input", "engine", "jsonl", "jsonl_uncompressed_sha256", "sidecar",
    "sidecar_uncompressed_sha256", "run", "run_sha256", "ezdxf_version",
    "requirements_sha256", "image", "records", "schema",
)


def render_rows(rows: list[dict]) -> str:
    out = [MANIFEST_MARK, ""]
    for r in rows:
        out.append("[[ground_truth]]")
        out.append(f'id = "{r["id"]}"')
        for key in MANIFEST_KEYS:
            if key == "file":
                continue
            value = r[key]
            out.append(f"{key} = {value}" if isinstance(value, int) else f'{key} = "{value}"')
        out.append("")
    return "\n".join(out)


def rewrite_manifest(text: str, rows: list[dict]) -> str:
    head = text.split(MANIFEST_MARK)[0].rstrip("\n") + "\n\n"
    return head + render_rows(rows)


def stage_rows(files: dict[str, bytes], manifest: dict, image: str) -> tuple[list[dict], dict[str, bytes]]:
    rows, store = [], {}
    for row in inputs(manifest):
        rid = row["id"]
        base = f"{rid}.{ENGINE}"
        jsonl, src, run = files[base + ".jsonl"], files[base + ".src.jsonl"], files[base + ".run.json"]
        meta = json.loads(run)
        rows.append({
            "id": rid, "input": rid, "engine": ENGINE,
            "jsonl": f"ground_truth/ezdxf/{base}.jsonl.zst",
            "jsonl_uncompressed_sha256": sha256(jsonl),
            "sidecar": f"ground_truth/ezdxf/{base}.src.jsonl.zst",
            "sidecar_uncompressed_sha256": sha256(src),
            "run": f"ground_truth/ezdxf/{base}.run.json",
            "run_sha256": sha256(run),
            "ezdxf_version": meta["ezdxf_version"],
            "requirements_sha256": meta["requirements_sha256"],
            "image": meta["image"],
            "records": meta["records"],
            "schema": SCHEMA,
        })
        store[f"{base}.jsonl.zst"] = compress(jsonl)
        store[f"{base}.src.jsonl.zst"] = compress(src)
        store[f"{base}.run.json"] = run
    return rows, store


def extract_locally(image: str) -> dict[str, bytes]:
    """The same extraction, in this process (already inside the pinned image)."""
    import tempfile

    os.environ["GT_IMAGE"] = image
    with tempfile.TemporaryDirectory() as tmp:
        ns = argparse.Namespace(
            manifest=str(MANIFEST), dxf_root=str(FIXTURES), out=tmp, only=None,
            requirements_sha256=None,
        )
        if command_extract(ns) != 0:
            sys.exit("extraction failed")
        return {p.name: p.read_bytes() for p in pathlib.Path(tmp).iterdir()}


def command_freeze(args) -> int:
    manifest = load_manifest()
    if args.runner == "local":
        files = extract_locally(args.image)
    else:
        files = run_extract_in_container(args.image, None)
    rows, store = stage_rows(files, manifest, args.image)
    committed = {r["id"]: r for r in manifest.get("ground_truth", [])}
    moved = []
    for r in rows:
        old = committed.get(r["id"])
        if old is None:
            moved.append(f"{r['id']}: new")
        elif old["jsonl_uncompressed_sha256"] != r["jsonl_uncompressed_sha256"]:
            moved.append(f"{r['id']}: records moved")
        elif old["sidecar_uncompressed_sha256"] != r["sidecar_uncompressed_sha256"]:
            moved.append(f"{r['id']}: sidecar moved")
    for m in moved:
        print(m)
    if not args.accept:
        print("nothing written (pass --accept to write)")
        return 1 if moved else 0
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for name, data in store.items():
        (OUT_DIR / name).write_bytes(data)
    text = MANIFEST.read_text(encoding="utf-8")
    MANIFEST.write_text(rewrite_manifest(text, rows), encoding="utf-8", newline="\n")
    print(f"wrote {len(store)} files and {len(rows)} manifest rows")
    return 0


def command_verify(_args) -> int:
    manifest = load_manifest()
    problems = []
    rows = manifest.get("ground_truth", [])
    listed = {r["input"] for r in rows}
    for row in inputs(manifest):
        if row["id"] not in listed:
            problems.append(f"{row['id']}: a DXF in the manifest with no ground truth row")
    if sorted(r["id"] for r in rows) != sorted(set(r["id"] for r in rows)):
        problems.append("duplicate ground truth ids")
    req = requirements_sha256()
    for r in rows:
        if r["requirements_sha256"] != req:
            problems.append(f"{r['id']}: made with requirements {r['requirements_sha256']}, tools/ground_truth/requirements.txt is {req}")
        if r["ezdxf_version"] != EZDXF_VERSION:
            problems.append(f"{r['id']}: ezdxf {r['ezdxf_version']}, the pin is {EZDXF_VERSION}")
        for key, hkey, packed in (("jsonl", "jsonl_uncompressed_sha256", True), ("sidecar", "sidecar_uncompressed_sha256", True), ("run", "run_sha256", False)):
            path = FIXTURES / r[key]
            if not path.is_file():
                problems.append(f"{r['id']}: {path} is missing")
                continue
            data = path.read_bytes()
            if packed:
                data = decompress(data)
            if sha256(data) != r[hkey]:
                problems.append(f"{r['id']}: {key} hashes to {sha256(data)}, the manifest froze {r[hkey]}")
        run = json.loads((FIXTURES / r["run"]).read_text(encoding="utf-8")) if (FIXTURES / r["run"]).is_file() else {}
        for k in ("ezdxf_version", "requirements_sha256", "image"):
            if run.get(k) != r[k]:
                problems.append(f"{r['id']}: run.json says {k} = {run.get(k)!r}, the manifest says {r[k]!r}")
        if not str(r["image"]).startswith(IMAGE.split("@")[0]) or "@sha256:" not in str(r["image"]):
            problems.append(f"{r['id']}: image {r['image']!r} is not a digest-pinned python image")
    for p in problems:
        print(p)
    if problems:
        return 1
    print(f"ground truths: {len(rows)} rows, every file is the one the manifest froze")
    return 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("extract")
    p.add_argument("--manifest", default=str(MANIFEST))
    p.add_argument("--dxf-root", default=str(FIXTURES))
    p.add_argument("--out", required=True)
    p.add_argument("--only", action="append")
    p.add_argument("--requirements-sha256", default=None)
    p.set_defaults(fn=command_extract)
    p = sub.add_parser("freeze")
    p.add_argument("--accept", action="store_true")
    p.add_argument("--image", default=IMAGE)
    p.add_argument(
        "--runner", choices=("docker", "local"), default="docker",
        help="docker: drive the pinned image; local: this process is already inside it",
    )
    p.set_defaults(fn=command_freeze)
    p = sub.add_parser("verify")
    p.set_defaults(fn=command_verify)
    args = ap.parse_args(argv)
    return args.fn(args)


if __name__ == "__main__":
    sys.exit(main())
