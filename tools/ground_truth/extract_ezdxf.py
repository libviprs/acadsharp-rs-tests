def p3(v):
    return (float(v[0]), float(v[1]), float(v[2]) if len(v) > 2 else 0.0)


def hexh(entity) -> str:
    handle = getattr(entity.dxf, "handle", None)
    return format(int(handle, 16), "X") if handle else "0"


class Extractor:
    def __init__(self, doc):
        self.doc = doc
        self.items = []  # (record dict, handles, dxf name)
        self.warnings = []  # (category, entity_type, detail, handles)
        self.active = set()

    # -- plumbing --
    def warn(self, category, entity_type, detail, path):
        self.warnings.append((category, entity_type, detail, list(path)))

    def emit(self, rec, path, dxf):
        self.items.append((rec, list(path), dxf))

    # -- one entity --
    def extract(self, e, view, xf, depth, inside_block, path):
        t = e.dxftype()
        here = path + [hexh(e)]
        if getattr(e.dxf, "invisible", 0):
            return
        if t in ("SEQEND", "BLOCK", "ENDBLK"):
            return
        if t == "LINE":
            self.emit(
                {"record": "line", "view": view, "a": xf.apply(p3(e.dxf.start)), "b": xf.apply(p3(e.dxf.end))},
                here, t)
        elif t == "POINT":
            self.emit({"record": "point", "view": view, "at": xf.apply(p3(e.dxf.location))}, here, t)
        elif t == "ARC":
            self.arc(e, view, xf, here)
        elif t == "CIRCLE":
            self.circle(e, view, xf, here)
        elif t == "ELLIPSE":
            self.ellipse(e, view, xf, here)
        elif t == "SPLINE":
            self.spline(e, view, xf, here)
        elif t == "LWPOLYLINE":
            elev = float(e.dxf.elevation) if e.dxf.hasattr("elevation") else 0.0
            pts = [(float(x), float(y), elev) for x, y, _b in e.get_points("xyb")]
            bul = [float(b) for _x, _y, b in e.get_points("xyb")]
            self.polyline(view, xf, p3(e.dxf.extrusion), pts, bul, bool(e.closed), here, t)
        elif t == "POLYLINE":
            if e.is_poly_face_mesh or e.is_polygon_mesh:
                self.warn("unsupported_entity", t, "no_canonical_mapping", here)
                return
            verts = [v for v in e.vertices if not (v.is_face_record if hasattr(v, "is_face_record") else False)]
            pts = [p3(v.dxf.location) for v in verts]
            if e.is_3d_polyline:
                self.polyline(view, xf, (0.0, 0.0, 1.0), pts, [0.0] * len(pts), bool(e.is_closed), here, t)
            else:
                bul = [float(v.dxf.bulge) if v.dxf.hasattr("bulge") else 0.0 for v in verts]
                self.polyline(view, xf, p3(e.dxf.extrusion), pts, bul, bool(e.is_closed), here, t)
        elif t == "SOLID":
            to_world = Xf.compose(xf, Xf.ocs(p3(e.dxf.extrusion)))
            corners = [p3(e.dxf.vtx0), p3(e.dxf.vtx1), p3(e.dxf.vtx3), p3(e.dxf.vtx2)]
            self.polygon(view, to_world, corners, here, t)
        elif t == "3DFACE":
            corners = [p3(e.dxf.vtx0), p3(e.dxf.vtx1), p3(e.dxf.vtx2), p3(e.dxf.vtx3)]
            self.polygon(view, xf, corners, here, t)
        elif t == "ATTDEF":
            if not inside_block:
                self.text(e, view, xf, here, t)
        elif t in ("TEXT", "ATTRIB"):
            self.text(e, view, xf, here, t)
        elif t == "MTEXT":
            self.mtext(e, view, xf, here, t)
        elif t == "HATCH":
            self.hatch(e, view, xf, here)
        elif t == "INSERT":
            self.insert(e, view, xf, depth, path, here)
        elif t == "DIMENSION":
            self.dimension(e, view, xf, depth, here)
        else:
            self.warn("unsupported_entity", t, "no_canonical_mapping", here)

    # -- curves --
    def circle(self, e, view, xf, here):
        to_world = Xf.compose(xf, Xf.ocs(p3(e.dxf.extrusion)))
        r = float(e.dxf.radius)
        m = map_curve(p3(e.dxf.center), (r, 0.0, 0.0), (0.0, r, 0.0), to_world)
        if m is None:
            self.warn("malformed_geometry", "CIRCLE", "degenerate_after_transform", here)
        elif m["circular"]:
            self.emit({"record": "circle", "view": view, "center": m["center"], "radius": m["radius"], "normal": m["normal"]}, here, "CIRCLE")
        else:
            self.emit({"record": "ellipse", "view": view, "center": m["center"], "major": m["major"], "ratio": m["ratio"], "start": 0.0, "end": TWO_PI, "normal": m["normal"]}, here, "CIRCLE")

    def arc(self, e, view, xf, here):
        to_world = Xf.compose(xf, Xf.ocs(p3(e.dxf.extrusion)))
        r = float(e.dxf.radius)
        m = map_curve(p3(e.dxf.center), (r, 0.0, 0.0), (0.0, r, 0.0), to_world)
        if m is None:
            self.warn("malformed_geometry", "ARC", "degenerate_after_transform", here)
            return
        s, en = sweep(math.radians(float(e.dxf.start_angle)), math.radians(float(e.dxf.end_angle)), m["offset"])
        if m["circular"]:
            self.emit({"record": "arc", "view": view, "center": m["center"], "radius": m["radius"], "start": s, "end": en, "normal": m["normal"]}, here, "ARC")
        else:
            self.emit({"record": "ellipse", "view": view, "center": m["center"], "major": m["major"], "ratio": m["ratio"], "start": s, "end": en, "normal": m["normal"]}, here, "ARC")

    def ellipse(self, e, view, xf, here):
        major = p3(e.dxf.major_axis)
        normal = p3(e.dxf.extrusion)
        minor = vscale(normalize(cross(normal, major)), length(major) * float(e.dxf.ratio))
        m = map_curve(p3(e.dxf.center), major, minor, xf)
        if m is None:
            self.warn("malformed_geometry", "ELLIPSE", "degenerate_after_transform", here)
            return
        sp, ep = float(e.dxf.start_param), float(e.dxf.end_param)
        s, en = sweep(sp, ep, m["offset"])
        if sp == ep or abs(ep - sp) >= TWO_PI:
            s = normalize_angle(sp + m["offset"])
            en = s + TWO_PI
        ratio = float(e.dxf.ratio) if xf.similarity else m["ratio"]
        self.emit({"record": "ellipse", "view": view, "center": m["center"], "major": m["major"], "ratio": ratio, "start": s, "end": en, "normal": m["normal"]}, here, "ELLIPSE")

    def spline(self, e, view, xf, here):
        control = [xf.apply(p3(p)) for p in e.control_points]
        fit = [xf.apply(p3(p)) for p in e.fit_points]
        if not control and not fit:
            self.warn("invalid_entity", "SPLINE", "no_control_or_fit_points", here)
            return
        flags = int(e.dxf.flags) if e.dxf.hasattr("flags") else 0
        self.emit({
            "record": "spline", "view": view, "degree": int(e.dxf.degree),
            "closed": bool(flags & 1), "periodic": bool(flags & 2),
            "control_points": control, "knots": [float(k) for k in e.knots],
            "weights": [float(w) for w in e.weights], "fit_points": fit,
        }, here, "SPLINE")

    def polyline(self, view, xf, normal, pts, bulges, closed, here, dxf):
        to_world = Xf.compose(xf, Xf.ocs(normal))
        u = to_world.vector((1.0, 0.0, 0.0))
        v = to_world.vector((0.0, 1.0, 0.0))
        wn = normalize(cross(u, v))
        if wn == (0.0, 0.0, 0.0):
            wn = (0.0, 0.0, 1.0)
        ax, ay, _ = arbitrary_axis(wn)
        out = []
        for local in pts:
            w = to_world.apply(local)
            out.append((dot(w, ax), dot(w, ay), dot(w, wn)))
        if not out:
            self.warn("invalid_entity", "Polyline", "no_vertices", here)
            return
        bulges = list(bulges) + [0.0] * max(0, len(out) - len(bulges))
        bulges = bulges[: len(out)]
        if not xf.similarity and any(b != 0.0 for b in bulges):
            self.warn("malformed_geometry", "Polyline", "non_uniform_scaled_bulge", here)
        self.emit({"record": "polyline", "view": view, "closed": closed, "normal": wn, "points": out, "bulges": bulges}, here, dxf)

    def polygon(self, view, to_world, corners, here, dxf):
        pts = []
        for c in corners:
            w = to_world.apply(c)
            if pts and pts[-1] == w:
                continue
            pts.append(w)
        if len(pts) >= 3:
            self.emit({"record": "polygon", "view": view, "points": pts}, here, dxf)

    # -- text --
    def text_common(self, view, xf, normal, anchor, height, rotation, width_factor, h, v, style, value, here, dxf):
        to_world = Xf.compose(xf, Xf.ocs(normal))
        base = to_world.vector((math.cos(rotation), math.sin(rotation), 0.0))
        up = to_world.vector((-math.sin(rotation), math.cos(rotation), 0.0))
        wn = normalize(cross(base, up))
        if wn == (0.0, 0.0, 0.0):
            self.warn("malformed_geometry", "Text", "degenerate_after_transform", here)
            return
        ax, ay, _ = arbitrary_axis(wn)
        w = to_world.apply(anchor)
        pos = (dot(w, ax), dot(w, ay), dot(w, wn))
        bl, ul = length(base), length(up)
        out_rot = normalize_angle(math.atan2(dot(base, ay), dot(base, ax)))
        out_h, out_w = height, width_factor
        if not xf.similarity:
            out_h = height * ul
            out_w = width_factor if ul == 0.0 else width_factor * bl / ul
        elif bl != 1.0:
            out_h = height * bl
        self.emit({
            "record": "text", "view": view, "at": pos, "height": out_h, "rotation": out_rot,
            "width_factor": out_w, "halign": h, "valign": v, "style": style,
            "text": normalize_newlines(value or ""),
        }, here, dxf)

    def text(self, e, view, xf, here, dxf):
        ha, va = int(e.dxf.halign), int(e.dxf.valign)
        use_align = ha != 0 or va != 0
        anchor = p3(e.dxf.align_point) if use_align and e.dxf.hasattr("align_point") else p3(e.dxf.insert)
        value = e.dxf.text
        if dxf in ("ATTRIB", "ATTDEF") and getattr(e, "has_embedded_mtext_entity", False):
            value = e.virtual_mtext_entity().text
        self.text_common(
            view, xf, p3(e.dxf.extrusion), anchor, float(e.dxf.height),
            math.radians(float(e.dxf.rotation)), float(e.dxf.width) if e.dxf.hasattr("width") else 1.0,
            H_NAMES.get(ha, "left"), V_NAMES.get(va, "baseline"), str(e.dxf.style), value, here, dxf)

    def mtext(self, e, view, xf, here, dxf):
        h, v = ATTACH.get(int(e.dxf.attachment_point), ("left", "top"))
        self.text_common(
            view, xf, p3(e.dxf.extrusion), p3(e.dxf.insert), float(e.dxf.char_height),
            math.radians(float(e.get_rotation())), 1.0, h, v, str(e.dxf.style), e.text, here, dxf)

    # -- hatch --
    def hatch(self, e, view, xf, here):
        to_world = Xf.compose(xf, Xf.ocs(p3(e.dxf.extrusion)))
        elev = float(e.dxf.elevation[2]) if e.dxf.hasattr("elevation") else 0.0
        if len(e.paths) == 0:
            self.warn("invalid_entity", "HATCH", "no_boundary_paths", here)
            return
        for path in e.paths:
            if type(path).__name__ == "PolylinePath":
                pts = [(float(x), float(y), elev) for x, y, *_ in path.vertices]
                bul = [float(b[2]) if len(b) > 2 else 0.0 for b in path.vertices]
                self.polyline(view, to_world, (0.0, 0.0, 1.0), pts, bul, bool(path.is_closed), here, "HATCH")
                continue
            if len(path.edges) == 0:
                self.warn("invalid_entity", "HATCH", "boundary_path_without_edges", here)
            for edge in path.edges:
                self.hatch_edge(edge, view, to_world, elev, here)

    def hatch_edge(self, edge, view, to_world, elev, here):
        kind = type(edge).__name__
        if kind == "LineEdge":
            self.emit({"record": "line", "view": view,
                       "a": to_world.apply((float(edge.start[0]), float(edge.start[1]), elev)),
                       "b": to_world.apply((float(edge.end[0]), float(edge.end[1]), elev))}, here, "HATCH")
        elif kind == "ArcEdge":
            r = float(edge.radius)
            m = map_curve((float(edge.center[0]), float(edge.center[1]), elev), (r, 0.0, 0.0), (0.0, r, 0.0), to_world)
            if m is None:
                self.warn("malformed_geometry", "HatchArc", "degenerate_after_transform", here)
                return
            # ezdxf hands back counter-clockwise angles whatever the edge's flag.
            s, en = sweep(math.radians(float(edge.start_angle)), math.radians(float(edge.end_angle)), m["offset"])
            if m["circular"]:
                self.emit({"record": "arc", "view": view, "center": m["center"], "radius": m["radius"], "start": s, "end": en, "normal": m["normal"]}, here, "HATCH")
            else:
                self.emit({"record": "ellipse", "view": view, "center": m["center"], "major": m["major"], "ratio": m["ratio"], "start": s, "end": en, "normal": m["normal"]}, here, "HATCH")
        elif kind == "EllipseEdge":
            major = (float(edge.major_axis[0]), float(edge.major_axis[1]), 0.0)
            minor = vscale(normalize(cross((0.0, 0.0, 1.0), major)), length(major) * float(edge.ratio))
            m = map_curve((float(edge.center[0]), float(edge.center[1]), elev), major, minor, to_world)
            if m is None:
                self.warn("malformed_geometry", "HatchEllipse", "degenerate_after_transform", here)
                return
            s, en = sweep(math.radians(float(edge.start_angle)), math.radians(float(edge.end_angle)), m["offset"])
            ratio = float(edge.ratio) if to_world.similarity else m["ratio"]
            self.emit({"record": "ellipse", "view": view, "center": m["center"], "major": m["major"], "ratio": ratio, "start": s, "end": en, "normal": m["normal"]}, here, "HATCH")
        elif kind == "SplineEdge":
            control = [to_world.apply((float(p[0]), float(p[1]), elev)) for p in edge.control_points]
            if not control:
                self.warn("invalid_entity", "HatchSpline", "no_control_points", here)
                return
            self.emit({
                "record": "spline", "view": view, "degree": int(edge.degree), "closed": False,
                "periodic": bool(edge.periodic), "control_points": control,
                "knots": [float(k) for k in edge.knot_values],
                "weights": [float(w) for w in edge.weights],
                "fit_points": [to_world.apply((float(p[0]), float(p[1]), elev)) for p in edge.fit_points],
            }, here, "HATCH")
        else:
            self.warn("unsupported_entity", "HatchEdge", str(kind), here)

    # -- blocks --
    def enter(self, name, depth, here):
        key = name.upper()
        if depth >= MAX_DEPTH:
            self.warn("malformed_geometry", "Insert", f"recursion_limit_{MAX_DEPTH}", here)
            return None
        if key in self.active:
            self.warn("malformed_geometry", "Insert", "cyclic_block_reference", here)
            return None
        self.active.add(key)
        return key

    def insert(self, e, view, xf, depth, path, here):
        name = str(e.dxf.name)
        block = self.doc.blocks.get(name)
        if block is None:
            self.warn("missing_reference", "Insert", "block_record_missing", here)
            return
        key = self.enter(name, depth, here)
        if key is None:
            return
        try:
            base = p3(block.block.dxf.base_point)
            cols = max(1, int(e.dxf.column_count))
            rows = max(1, int(e.dxf.row_count))
            if cols * rows > MAX_ARRAY_COPIES:
                self.warn("malformed_geometry", "Insert", f"array_too_large_{MAX_ARRAY_COPIES}", here)
                cells = [(0, 0)]
            else:
                cells = [(c, r) for r in range(rows) for c in range(cols)]
            for col, row in cells:
                t = Xf.translation((-base[0], -base[1], -base[2]))
                t = Xf.compose(Xf.scaling(float(e.dxf.xscale), float(e.dxf.yscale), float(e.dxf.zscale)), t)
                if col or row:
                    t = Xf.compose(Xf.translation((col * float(e.dxf.column_spacing), row * float(e.dxf.row_spacing), 0.0)), t)
                t = Xf.compose(Xf.rotation_z(math.radians(float(e.dxf.rotation))), t)
                t = Xf.compose(Xf.translation(p3(e.dxf.insert)), t)
                child = Xf.compose(xf, Xf.compose(Xf.ocs(p3(e.dxf.extrusion)), t))
                for sub in block:
                    self.extract(sub, view, child, depth + 1, True, here)
        finally:
            self.active.discard(key)
        # The insert's own ATTRIBs sit in the space that contains the insert.
        for attrib in e.attribs:
            self.extract(attrib, view, xf, depth, False, here)

    def dimension(self, e, view, xf, depth, here):
        name = e.dxf.geometry if e.dxf.hasattr("geometry") else ""
        block = self.doc.blocks.get(name) if name else None
        if block is None:
            self.warn("missing_reference", "Dimension", "dimension_block_missing", here)
            return
        key = self.enter(name, depth, here)
        if key is None:
            return
        try:
            for sub in block:
                self.extract(sub, view, xf, depth + 1, True, here)
        finally:
            self.active.discard(key)


def views_of(doc):
    """Layouts in tab order, then by name ordinally. Model space is tab 0."""
    rows = []
    for layout in doc.layouts:
        order = 0 if layout.is_modelspace else int(layout.dxf.taborder)
        rows.append((order, layout.name, layout))
    rows.sort(key=lambda r: (r[0], r[1]))
    return rows


def extract_document(doc, version: str):
    """Everything in `doc` as (records, sidecar entries), in schema order."""
    x = Extractor(doc)
    heads = [{
        "record": "document", "format": "dxf", "acad_version": version,
        "maintenance_version": int(doc.header.get("$ACADMAINTVER", 0) or 0),
    }]
    for index, (_order, name, layout) in enumerate(views_of(doc)):
        heads.append({"record": "view", "index": index, "name": name,
                      "kind": "model" if layout.is_modelspace else "layout"})
        for entity in layout:
            x.extract(entity, index, Xf(), 0, False, [])
    records = []
    sidecar = []
    for rec in heads:
        records.append(rec)
        sidecar.append((["0"], None))
    for rec, handles, dxf in x.items:
        records.append(rec)
        sidecar.append((handles, dxf))
    for category, etype, detail, handles in sorted(x.warnings, key=lambda w: w[:3]):
        records.append({"record": "warning", "category": category, "entity_type": etype, "detail": detail})
        sidecar.append((handles, None))
    return records, sidecar


def emit_texts(records, sidecar):
    jsonl = "".join(render(r) + "\n" for r in records)
    src = "".join(
        render_sidecar_line(i, h, r["record"], d) + "\n"
        for i, (r, (h, d)) in enumerate(zip(records, sidecar))
    )
    return jsonl, src


# ------------------------------------------------------------------- inputs ---


def load_manifest(path=MANIFEST) -> dict:
    with open(path, "rb") as fh:
        return tomllib.load(fh)


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def inputs(manifest: dict) -> list[dict]:
    """Every DXF the manifest lists. All of them: the twins of a DWG, and the
    AC1009 and geoloc_AC1021 files that are inputs for R5 and compared with
    nothing yet."""
    return list(manifest.get("oracle_input", []))


def requirements_sha256() -> str:
    return sha256(REQUIREMENTS.read_bytes())


def command_extract(args) -> int:
    import ezdxf  # only here: `freeze` and `verify` must run without it

    manifest = load_manifest(pathlib.Path(args.manifest))
    root = pathlib.Path(args.dxf_root)
    out = pathlib.Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    image = os.environ.get("GT_IMAGE", "")
    wanted = set(args.only or [])
    done = 0
    failed = 0
    for row in inputs(manifest):
        if wanted and row["id"] not in wanted:
            continue
        path = root / row["file"]
        data = path.read_bytes()
        if sha256(data) != row["sha256"]:
            print(f"{row['id']}: {path} is not the file the manifest froze", file=sys.stderr)
            return 1
        try:
            doc = ezdxf.readfile(str(path))
            records, sidecar = extract_document(doc, doc.dxfversion)
        except Exception:  # report every input's failure, then fail the run
            import traceback

            print(f"{row['id']}: FAILED", file=sys.stderr)
            traceback.print_exc()
            failed += 1
            continue
        jsonl, src = emit_texts(records, sidecar)
        run = {
            "engine": ENGINE,
            "ezdxf_version": ezdxf.__version__,
            "python": ".".join(map(str, sys.version_info[:3])),
            "requirements_sha256": args.requirements_sha256 or requirements_sha256(),
            "image": image,
            "input": row["id"],
            "input_file": row["file"],
            "input_sha256": row["sha256"],
            "dxf_version": doc.dxfversion,
            "records": len(records),
        }
        base = out / f"{row['id']}.{ENGINE}"
        (base.with_name(base.name + ".jsonl")).write_text(jsonl, encoding="utf-8", newline="\n")
        (base.with_name(base.name + ".src.jsonl")).write_text(src, encoding="utf-8", newline="\n")
        (base.with_name(base.name + ".run.json")).write_text(
            json.dumps(run, indent=2, sort_keys=True) + "\n", encoding="utf-8", newline="\n")
        done += 1
        print(f"{row['id']}: {len(records)} records")
    if failed:
        return 1
    if wanted and done != len(wanted):
        print("some --only ids are not in the manifest", file=sys.stderr)
        return 1
    return 0


