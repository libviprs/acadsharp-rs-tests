#!/usr/bin/env python3
"""Make and verify the round-trip matrix's outputs (R5.3, acadsharp-rs-tests#29).

`fixtures/written_plan.toml` says which library rewrites which drawing at which
version in which container. This tool produces the files for the two writers,
freezes the oracle's reading of each one, and records every output as a
`[[written]]` row of `fixtures/manifest.toml`. The files live compressed under
`fixtures/written/`; the manifest holds the sha256 of the uncompressed bytes, so
the contract is on the bytes a writer wrote and not on one zstd frame.

    python3 tools/regenerate_written.py verify
    python3 tools/regenerate_written.py regenerate --acadrust-dir DIR
    python3 tools/regenerate_written.py regenerate --acadrust-dir DIR --accept

Two writers, two sources of bytes:

* ACadSharp rewrites through the oracle's `--rewrite-to`, in the SDK container,
  twice per output. Two writes of one output that differ are a failure of the
  run, not a row: a matrix of files that move between runs judges nothing.
* acadrust's files come from `src/bin/rewrite-acadrust.rs` (it does the same
  twice-and-compare), run in the Rust container; this tool takes the directory
  it wrote with `--acadrust-dir`. The two stages are separate processes in
  separate images on purpose, and neither can quietly stand in for the other.

A write a library refuses or fails is a row with `write_failed = "<its own
message>"` and no file, so the absence of an output is a recorded fact.

`regenerate` never touches a committed file without `--accept`, for the reason
`tools/regenerate_reference.py` gives: a moved output has to arrive as a
reviewed diff. Needs Python 3.14 (it imports that tool's zstd settings).
"""

from __future__ import annotations

import argparse
import pathlib
import shutil
import subprocess
import sys
import tempfile
import tomllib

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))

import regenerate_reference as ref  # noqa: E402

ROOT = ref.ROOT
MANIFEST = ref.MANIFEST
FIXTURE_DIR = ref.FIXTURE_DIR
WRITTEN_DIR = FIXTURE_DIR / "written"
PLAN = FIXTURE_DIR / "written_plan.toml"
ACADRUST_REV = ROOT / "ACADRUST_REV"

MARK = "# ---- written outputs: generated by tools/regenerate_written.py, do not edit ----"
END = "# ---- end of the written outputs ----"

# The oracle's --as names for the plan's containers.
ORACLE_AS = {"dwg": "dwg", "dxf-ascii": "dxf", "dxf-binary": "dxf-binary"}

ROW_KEYS = (
    "writer", "source", "container", "version", "file", "bytes", "sha256",
    "generated_by", "writer_version", "write_failed",
    "reference_jsonl", "reference_jsonl_uncompressed_sha256", "no_reference",
    "acadsharp_reference_version", "acadsharp_reference_commit", "dotnet_sdk",
    "reference_schema",
)
INT_KEYS = frozenset({"bytes", "reference_schema"})


def load_plan() -> dict:
    with PLAN.open("rb") as handle:
        return tomllib.load(handle)


def output_id(writer: str, source: str, container: str, version: str) -> str:
    """The `[[written]]` id. Kept in step with `Output::id` in src/written.rs, and
    `tests/written.rs` holds the two to the same list."""
    short = source.removeprefix("acadsharp-")
    return f"w-{writer}-{short}-{container}-{version.lower()}"


def outputs(plan: dict) -> list[dict]:
    result = []
    for stage in plan["stage"].values():
        for source in stage["sources"]:
            for writer, spec in plan["writer"].items():
                for version in spec.get("dwg", []):
                    result.append(("dwg", writer, source, version))
                for version in spec.get("dxf", []):
                    result.append(("dxf-ascii", writer, source, version))
                    result.append(("dxf-binary", writer, source, version))
    rows = []
    for container, writer, source, version in sorted(result, key=lambda t: (t[1], t[2], t[0], t[3])):
        rows.append({
            "id": output_id(writer, source, container, version),
            "writer": writer, "source": source, "container": container, "version": version,
            "ext": "dwg" if container == "dwg" else "dxf",
        })
    return sorted(rows, key=lambda r: r["id"])


def pinned_acadrust() -> str:
    for line in ACADRUST_REV.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line and not line.startswith("#"):
            return line
    raise SystemExit(f"{ACADRUST_REV} holds no pin")


def render_rows(rows: list[dict]) -> str:
    out = [MARK, ""]
    for row in rows:
        out.append("[[written]]")
        out.append(f'id = "{row["id"]}"')
        for key in ROW_KEYS:
            if key not in row:
                continue
            value = row[key]
            out.append(f"{key} = {value}" if key in INT_KEYS else f'{key} = "{value}"')
        out.append("")
    out.append(END)
    return "\n".join(out) + "\n"


def rewrite_manifest(text: str, rows: list[dict]) -> str:
    """Replace what sits between the two markers (or append the block), and
    nothing else."""
    block = render_rows(rows)
    if MARK in text:
        head, _, rest = text.partition(MARK)
        tail = rest.partition(END)[2] if END in rest else ""
        tail = tail.lstrip("\n")
        return head.rstrip("\n") + "\n\n" + block + (("\n" + tail) if tail else "")
    return text.rstrip("\n") + "\n\n" + block


def first_line(text: str) -> str:
    for line in text.splitlines():
        if line.strip():
            return line.strip()
    return ""


# ------------------------------------------------------------------ verify ---


def command_verify(_args: argparse.Namespace) -> int:
    manifest = ref.load_manifest()
    plan = load_plan()
    want = {o["id"]: o for o in outputs(plan)}
    rows = manifest.get("written", [])
    problems: list[str] = []
    have = {r["id"]: r for r in rows}
    for missing in sorted(set(want) - set(have)):
        problems.append(f"{missing}: in the plan and not in the manifest")
    for extra in sorted(set(have) - set(want)):
        problems.append(f"{extra}: in the manifest and not in the plan")
    acadrust = pinned_acadrust()
    locked = ref.locked_acadsharp_version()
    for row in rows:
        rid = row["id"]
        spec = want.get(rid)
        if spec is None:
            continue
        for key in ("writer", "source", "container", "version"):
            if row.get(key) != spec[key]:
                problems.append(f"{rid}: {key} is {row.get(key)!r}, the plan says {spec[key]!r}")
        expected_writer = f"acadrust@{acadrust}" if row["writer"] == "acadrust" else f"ACadSharp {locked}"
        if row.get("writer_version") != expected_writer:
            problems.append(f"{rid}: writer_version {row.get('writer_version')!r}, expected {expected_writer!r}")
        if row.get("write_failed"):
            if "file" in row or "sha256" in row:
                problems.append(f"{rid}: write_failed and a file")
            continue
        if row["writer"] == "acadrust":
            # Not stored: the test makes it again and holds it to this hash.
            if "file" in row:
                problems.append(f"{rid}: an acadrust output is made by the test, not stored")
            if "sha256" not in row:
                problems.append(f"{rid}: no sha256 for the output the test has to reproduce")
        else:
            if "file" not in row:
                problems.append(f"{rid}: an ACadSharp output with no stored file")
                continue
            path = FIXTURE_DIR / row["file"]
            if not path.is_file():
                problems.append(f"{rid}: {path} is missing")
                continue
            try:
                data = ref.decompress(path.read_bytes())
            except ref.zstd.ZstdError as error:
                problems.append(f"{rid}: {path} does not decompress: {error}")
                continue
            if ref.sha256_bytes(data) != row["sha256"] or len(data) != row["bytes"]:
                problems.append(f"{rid}: the output is not the bytes the manifest froze")
        if row.get("no_reference"):
            if "reference_jsonl" in row:
                problems.append(f"{rid}: no_reference and a reference")
            continue
        if "reference_jsonl" not in row:
            problems.append(f"{rid}: no oracle reading and no no_reference reason")
            continue
        rpath = FIXTURE_DIR / row["reference_jsonl"]
        if not rpath.is_file():
            problems.append(f"{rid}: {rpath} is missing")
            continue
        reading = ref.decompress(rpath.read_bytes())
        if ref.sha256_bytes(reading) != row["reference_jsonl_uncompressed_sha256"]:
            problems.append(f"{rid}: the oracle's reading is not the one the manifest froze")
    for problem in problems:
        print(f"error: {problem}", file=sys.stderr)
    if problems:
        print(f"{len(problems)} problem(s)", file=sys.stderr)
        return 1
    print(f"verified {len(rows)} written output(s) against fixtures/manifest.toml")
    return 0


# -------------------------------------------------------------- regenerate ---


def oracle(dotnet: list[str], *args: str) -> subprocess.CompletedProcess:
    command = dotnet + ["run", "--no-build", "--no-restore", "-c", "Release",
                        "--project", "reference/ACadSharp.Reference", "--", *args]
    print("$ " + " ".join(command))
    return subprocess.run(command, cwd=ROOT, check=False, capture_output=True, text=True)


def command_regenerate(args: argparse.Namespace) -> int:
    manifest = ref.load_manifest()
    problems = ref.verify_inputs(manifest)
    if problems:
        for problem in problems:
            print(f"error: {problem}", file=sys.stderr)
        return 1
    plan = load_plan()
    wanted = outputs(plan)
    acadsharp = ref.locked_acadsharp_version()
    sdk = ref.pinned_sdk_version()
    if acadsharp is None or sdk is None:
        print("error: the oracle's package or SDK pin is unreadable", file=sys.stderr)
        return 1
    acadrust_dir = pathlib.Path(args.acadrust_dir) if args.acadrust_dir else None
    if any(o["writer"] == "acadrust" for o in wanted) and acadrust_dir is None:
        print("error: the plan has acadrust outputs and --acadrust-dir was not given. Run "
              "src/bin/rewrite-acadrust.rs first (in the Rust container) and pass its directory.",
              file=sys.stderr)
        return 1
    sources = {f["id"]: f for f in manifest["fixture"]}

    with tempfile.TemporaryDirectory(prefix="acadsharp-written-") as staging_name:
        staging = pathlib.Path(staging_name)
        ref.STAGING_MOUNT[0] = str(staging)
        dotnet = ref.choose_runner(args.runner, args.image)
        in_container = dotnet[0] == "docker"
        mount = "/staging" if in_container else str(staging)
        ref.run(dotnet + ["restore", "reference/ACadSharp.Reference/ACadSharp.Reference.csproj",
                          "--locked-mode", "-v", "q"], what="dotnet restore --locked-mode")
        ref.run(dotnet + ["build", "reference/ACadSharp.Reference/ACadSharp.Reference.csproj",
                          "-c", "Release", "--no-restore", "-v", "q"], what="dotnet build")
        for sub in ("gen1", "gen2", "files", "read"):
            (staging / sub).mkdir()

        rows: list[dict] = []
        for o in wanted:
            rid, ext = o["id"], o["ext"]
            row = {"id": rid, "writer": o["writer"], "source": o["source"],
                   "container": o["container"], "version": o["version"]}
            if o["writer"] == "acadsharp":
                row["generated_by"] = "reference/ACadSharp.Reference --rewrite-to (tools/regenerate_written.py)"
                row["writer_version"] = f"ACadSharp {acadsharp}"
                source = f"fixtures/{sources[o['source']]['file']}"
                failure = None
                for n in ("gen1", "gen2"):
                    done = oracle(dotnet, source, "--rewrite-to", f"{mount}/{n}/{rid}.{ext}",
                                  "--as", ORACLE_AS[o["container"]], "--version", o["version"])
                    if done.returncode != 0:
                        failure = first_line(done.stderr) or f"exit {done.returncode}"
                        break
                if failure:
                    row["write_failed"] = failure
                    rows.append(row)
                    print(f"  {rid}: write failed: {failure}")
                    continue
                a, b = (staging / n / f"{rid}.{ext}" for n in ("gen1", "gen2"))
                if a.read_bytes() != b.read_bytes():
                    print(f"error: {rid}: two writes of one output differ", file=sys.stderr)
                    return 1
                shutil.copy(a, staging / "files" / f"{rid}.{ext}")
            else:
                row["generated_by"] = "src/bin/rewrite-acadrust.rs (tools/regenerate_written.py)"
                row["writer_version"] = f"acadrust@{pinned_acadrust()}"
                error = acadrust_dir / f"{rid}.error.txt"
                produced = acadrust_dir / f"{rid}.{ext}"
                if error.is_file():
                    row["write_failed"] = first_line(error.read_text(encoding="utf-8"))
                    rows.append(row)
                    print(f"  {rid}: write failed: {row['write_failed']}")
                    continue
                if not produced.is_file():
                    print(f"error: {rid}: {produced} is not in --acadrust-dir", file=sys.stderr)
                    return 1
                shutil.copy(produced, staging / "files" / f"{rid}.{ext}")
            data = (staging / "files" / f"{rid}.{ext}").read_bytes()
            # ACadSharp's outputs are stored: nothing offline can make them again.
            # acadrust's are not: its writer is deterministic and is run in the
            # test itself (`rewrite-acadrust` is its own control), so storing 14 MB
            # of them would only be a second copy of what a build makes, and the
            # fixtures directory has a size budget (fixtures/README.md).
            if o["writer"] == "acadsharp":
                row["file"] = f"written/{rid}.{ext}.zst"
            row["bytes"] = len(data)
            row["sha256"] = ref.sha256_bytes(data)
            # The oracle's reading, one output at a time: a file it cannot read
            # is a row with its reason, never a hole in the run.
            done = oracle(dotnet, f"{mount}/files/{rid}.{ext}", "--jsonl",
                          f"{mount}/read/{rid}.reference.jsonl")
            reading = staging / "read" / f"{rid}.reference.jsonl"
            if done.returncode != 0 or not reading.is_file():
                row["no_reference"] = first_line(done.stderr) or f"exit {done.returncode}"
                print(f"  {rid}: the oracle cannot read it: {row['no_reference']}")
            else:
                jsonl = reading.read_bytes()
                row["reference_jsonl"] = f"written/{rid}.reference.jsonl.zst"
                row["reference_jsonl_uncompressed_sha256"] = ref.sha256_bytes(jsonl)
                row["acadsharp_reference_version"] = acadsharp
                row["acadsharp_reference_commit"] = manifest["upstream"]["commit"]
                row["dotnet_sdk"] = sdk
                row["reference_schema"] = ref.REFERENCE_SCHEMA
            rows.append(row)

        committed = {r["id"]: r for r in manifest.get("written", [])}
        changed = []
        for row in rows:
            old = committed.get(row["id"])
            if old is None:
                changed.append(f"{row['id']}: new")
            elif any(old.get(k) != row.get(k) for k in ROW_KEYS):
                changed.append(f"{row['id']}: moved")
        for gone in sorted(set(committed) - {r["id"] for r in rows}):
            changed.append(f"{gone}: no longer in the plan")
        for line in changed:
            print(f"  {line}")
        if not changed:
            print("no differences; nothing to accept")
            return 0
        if not args.accept:
            print(f"\n{len(changed)} difference(s) and --accept was not given, so nothing was written.")
            return 1

        WRITTEN_DIR.mkdir(parents=True, exist_ok=True)
        for row in rows:
            if "file" in row:
                data = (staging / "files" / pathlib.Path(row["file"]).name.removesuffix(".zst")).read_bytes()
                (FIXTURE_DIR / row["file"]).write_bytes(ref.compress(data))
            elif row["writer"] == "acadsharp" and "write_failed" not in row:
                raise SystemExit(f"{row['id']}: an ACadSharp output with no stored file")
            if "reference_jsonl" in row:
                jsonl = (staging / "read" / f"{row['id']}.reference.jsonl").read_bytes()
                (FIXTURE_DIR / row["reference_jsonl"]).write_bytes(ref.compress(jsonl))
        MANIFEST.write_text(rewrite_manifest(MANIFEST.read_text(encoding="utf-8"), rows),
                            encoding="utf-8")
        print(f"\naccepted: wrote {len(rows)} written row(s)")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="command")
    verify = sub.add_parser("verify", help="check the committed outputs; never runs .NET")
    verify.set_defaults(handler=command_verify)
    regenerate = sub.add_parser("regenerate", help="write the outputs and freeze the oracle's reading")
    regenerate.add_argument("--accept", action="store_true")
    regenerate.add_argument("--acadrust-dir", help="the directory src/bin/rewrite-acadrust.rs wrote")
    regenerate.add_argument("--runner", choices=("auto", "dotnet", "docker"), default="auto")
    regenerate.add_argument("--image", default=ref.DEFAULT_IMAGE)
    regenerate.set_defaults(handler=command_regenerate)
    args = parser.parse_args(argv)
    if not getattr(args, "handler", None):
        args = parser.parse_args(["verify"])
    return args.handler(args)


if __name__ == "__main__":
    raise SystemExit(main())
